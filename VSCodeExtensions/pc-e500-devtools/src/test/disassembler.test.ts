// The disassembler: what it writes assembles back to the same bytes, whatever they are.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { describe, it } from "node:test";
import { assemble } from "../asm/assembler";
import { disassemble, DisassemblyError, readImage } from "../asm/disassembler";
import { loadMFile } from "../project/loadM";

const back = (bytes: Uint8Array, origin: number): void => {
  for (const options of [{}, { labels: false, addresses: false, bytes: false }]) {
    const { source } = disassemble(readImage(bytes, "raw", origin), options);
    const result = assemble(source);
    assert.deepEqual(result.issues.filter(i => i.severity === "error"), []);
    assert.equal(result.origin, origin);
    assert.ok(Buffer.from(result.binary).equals(Buffer.from(bytes)));
  }
};

// Every opcode with several second bytes, and every PRE before every opcode.
const opcodes: number[] = [], prefixes: number[] = [];
for (let a = 0; a < 256; a++) for (const b of [0x00, 0x12, 0x24, 0x34, 0x45, 0x84, 0xc5, 0xff]) opcodes.push(a, b, 0x12, 0x34, 0x05, 0x00, 0x00);
for (const p of [0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37]) for (let a = 0; a < 256; a++) prefixes.push(p, a, 0x24, 0x10, 0x20, 0x30, 0x00);

describe("disassembler", () => {
  it("assembles back to the same bytes", () => {
    back(Uint8Array.from(opcodes), 0x20000);
    back(Uint8Array.from(prefixes), 0x80000);
    for (let n = 1; n <= 5; n++) back(Uint8Array.from(opcodes.slice(0, n)), 0xbec00);
    let seed = 12345;
    back(Uint8Array.from({ length: 70000 }, () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) >> 16 & 255), 0xb8000);
  });

  it("writes labels, data and notes", () => {
    const { source, instructions, dataBytes } = disassemble(readImage(Uint8Array.of(0x1b, 0x02, 0x9f, 0x07, 0x20, 0x4c, 0x4c), "raw", 0xbec00));
    assert.match(source, /^; Generated by e500dasm[^\n]*\n; Input: RAW, 7 bytes\n        ORG \$BEC00\n\nLBEC00:\n        JRNZ   LBEC00 /);
    assert.match(source, /DB     \$20 +; BEC04 \| 20 \| reserved opcode/);
    assert.match(source, /byte-preserving fallback; decoded: SUB X, X\n        END\n$/);
    assert.deepEqual([instructions, dataBytes], [3, 3]);
  });

  it("reads SAVE M files, and refuses what is not one", () => {
    const file = loadMFile(0xbec00, Uint8Array.of(0x9f, 0x07));
    const read = readImage(file, "ce140f");
    assert.deepEqual([read.origin, read.payload.length], [0xbec00, 2]);
    assert.match(disassemble(read).source, /CE-140F header: FF 00 06 01 10 02 00 00 00 EC 0B FF FF FF 00 0F\n/);
    for (const bad of [() => readImage(file.slice(0, 10), "ce140f"), () => readImage(file.slice(0, 17), "ce140f"), () => readImage(file, "ce140f", 1), () => readImage(file, "raw"), () => readImage(file, "raw", 0xfffff)]) assert.throws(bad, DisassemblyError);
  });

  const native = path.resolve(__dirname, "..", "..", "..", "..", "DisAssembler", "app", process.platform === "win32" ? "e500dasm.exe" : "e500dasm");
  it("writes what e500dasm writes", { skip: fs.existsSync(native) ? false : "e500dasm is not built" }, () => {
    const folder = fs.mkdtempSync(path.join(os.tmpdir(), "e500dis-"));
    try {
      for (const [bytes, origin] of [[opcodes, 0x20000], [prefixes, 0x80000], [opcodes.slice(0, 9000), 0xe000]] as Array<[number[], number]>) {
        const input = path.join(folder, "i.bin"), output = path.join(folder, "o.asm");
        fs.writeFileSync(input, Uint8Array.from(bytes));
        const r = spawnSync(native, [input, "--format", "raw", "--org", origin.toString(16), "-o", output], { encoding: "utf8" });
        assert.equal(r.status, 0, r.stderr);
        assert.ok(fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") === disassemble(readImage(Uint8Array.from(bytes), "raw", origin)).source);
      }
    } finally { fs.rmSync(folder, { recursive: true, force: true }); }
  });
});
