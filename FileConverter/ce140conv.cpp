static uint32_t parseUint(const std::string& s) {
    uint32_t v = 0;
    const char* p = s.c_str();
    if ((p[0] == '0' && (p[1] == 'x' || p[1] == 'X')) || p[0] == '$') {
        p += (p[0] == '$') ? 1 : 2;
        if (sscanf(p, "%x", &v) != 1) die("bad number: " + s);
    } else if (p[0] == '&' && (p[1] == 'H' || p[1] == 'h')) {
        if (sscanf(p + 2, "%x", &v) != 1) die("bad number: " + s);
    } else {
        if (sscanf(p, "%u", &v) != 1) die("bad number: " + s);
    }
    return v;
}

int main(int argc, char** argv) {
    if (argc < 2) { usage(); return 1; }
    std::string cmd = argv[1];
    if (cmd == "-h" || cmd == "--help" || cmd == "help") { usage(); return 0; }

    // collect positionals and options
    std::vector<std::string> pos;
    Options o;
    for (int i = 2; i < argc; i++) {
        std::string a = argv[i];
        auto need = [&](const char* name) -> std::string {
            if (i + 1 >= argc) die(std::string("missing value for ") + name);
            return argv[++i];
        };
        if      (a == "--sjis")   o.sjis = true;
        else if (a == "--cr")     o.sharpCR = true;
        else if (a == "--no-eof") o.noEof = true;
        else if (a == "--lf")     o.hostLF = true;
        else if (a == "--ascii")  o.asciiOnly = true;
        else if (a == "--addr")   { o.addr = parseUint(need("--addr")); o.haveAddr = true; }
        else if (a == "--header") o.headerFile = need("--header");
        else if (a == "--save-header") o.saveHeader = need("--save-header");
        else if (a == "--charset") o.charsetFile = need("--charset");
        else if (!a.empty() && a[0] == '-') die("unknown option: " + a);
        else pos.push_back(a);
    }

    // load charset for text modes
    Charset cs;
    cs.buildDefault();
    if (!o.asciiOnly && (cmd == "text2bas" || cmd == "bas2text")) {
        std::string path = o.charsetFile;
        if (path.empty()) {
            // try next to the exe, then current dir
            std::string exeDir = dirOf(argv[0]);
            std::string cand1 = exeDir + "charset_e500.tab";
            std::ifstream t1(cand1);
            if (t1) path = cand1;
            else {
                std::ifstream t2("charset_e500.tab");
                if (t2) path = "charset_e500.tab";
            }
        }
        if (!path.empty()) {
            std::string err;
            if (!cs.loadFile(path, &err)) die(err);
            std::cerr << "ce140conv: using charset table " << path << "\n";
        } else if (o.charsetFile.empty()) {
            std::cerr << "ce140conv: note: no charset_e500.tab found; using "
                         "built-in ASCII + PUA fallback only\n";
        }
    }

    auto needPos = [&](size_t n) {
        if (pos.size() < n) { usage(); die("missing file argument(s)"); }
    };

    if (cmd == "text2bas") { needPos(2); return text2bas(pos[0], pos[1], cs, o); }
    if (cmd == "bas2text") { needPos(2); return bas2text(pos[0], pos[1], cs, o); }
    if (cmd == "bin2bas")  { needPos(2); return bin2bas(pos[0], pos[1], o); }
    if (cmd == "bas2bin")  { needPos(2); return bas2bin(pos[0], pos[1], o); }
    if (cmd == "info")     { needPos(1); return info(pos[0]); }

    usage();
    die("unknown command: " + cmd);
    return 2;
}
