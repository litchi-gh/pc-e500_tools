using Bytes = std::vector<uint8_t>;

static void die(const std::string& msg) {
    std::cerr << "ce140conv: error: " << msg << "\n";
    std::exit(2);
}

static Bytes readFile(const std::string& path) {
    std::ifstream f(path, std::ios::binary);
    if (!f) die("cannot open input file: " + path);
    return Bytes((std::istreambuf_iterator<char>(f)),
                 std::istreambuf_iterator<char>());
}

static void writeFile(const std::string& path, const Bytes& data) {
    std::ofstream f(path, std::ios::binary | std::ios::trunc);
    if (!f) die("cannot open output file: " + path);
    if (!data.empty())
        f.write(reinterpret_cast<const char*>(data.data()),
                static_cast<std::streamsize>(data.size()));
    if (!f) die("write failed: " + path);
}

// directory part of a path (including trailing separator), or "" if none
static std::string dirOf(const std::string& path) {
    size_t p = path.find_last_of("/\\");
    return (p == std::string::npos) ? std::string() : path.substr(0, p + 1);
}

// ----------------------------------------------------------------------------
// UTF-8 <-> Unicode code points
// ----------------------------------------------------------------------------
static std::vector<uint32_t> utf8ToCodepoints(const Bytes& in) {
    std::vector<uint32_t> out;
    size_t i = 0, n = in.size();
    // skip UTF-8 BOM
    if (n >= 3 && in[0] == 0xEF && in[1] == 0xBB && in[2] == 0xBF) i = 3;
    while (i < n) {
        uint32_t c = in[i];
        size_t extra;
        uint32_t cp;
        if (c < 0x80)       { cp = c;          extra = 0; }
        else if ((c >> 5) == 0x6) { cp = c & 0x1F; extra = 1; }
        else if ((c >> 4) == 0xE) { cp = c & 0x0F; extra = 2; }
        else if ((c >> 3) == 0x1E){ cp = c & 0x07; extra = 3; }
        else { cp = 0xFFFD; extra = 0; } // invalid lead byte
        if (i + extra >= n) { out.push_back(0xFFFD); break; }
        bool ok = true;
        for (size_t k = 1; k <= extra; k++) {
            uint8_t cc = in[i + k];
            if ((cc >> 6) != 0x2) { ok = false; break; }
            cp = (cp << 6) | (cc & 0x3F);
        }
        if (!ok) { out.push_back(0xFFFD); i++; continue; }
        out.push_back(cp);
        i += extra + 1;
    }
    return out;
}

static void appendUtf8(Bytes& out, uint32_t cp) {
    if (cp < 0x80) {
        out.push_back(static_cast<uint8_t>(cp));
    } else if (cp < 0x800) {
        out.push_back(static_cast<uint8_t>(0xC0 | (cp >> 6)));
        out.push_back(static_cast<uint8_t>(0x80 | (cp & 0x3F)));
    } else if (cp < 0x10000) {
        out.push_back(static_cast<uint8_t>(0xE0 | (cp >> 12)));
        out.push_back(static_cast<uint8_t>(0x80 | ((cp >> 6) & 0x3F)));
        out.push_back(static_cast<uint8_t>(0x80 | (cp & 0x3F)));
    } else {
        out.push_back(static_cast<uint8_t>(0xF0 | (cp >> 18)));
        out.push_back(static_cast<uint8_t>(0x80 | ((cp >> 12) & 0x3F)));
        out.push_back(static_cast<uint8_t>(0x80 | ((cp >> 6) & 0x3F)));
        out.push_back(static_cast<uint8_t>(0x80 | (cp & 0x3F)));
    }
}

#ifdef _WIN32
// Shift-JIS (CP932) <-> Unicode code points, Windows only
static std::vector<uint32_t> sjisToCodepoints(const Bytes& in) {
    std::vector<uint32_t> out;
    if (in.empty()) return out;
    int wn = MultiByteToWideChar(932, 0, reinterpret_cast<const char*>(in.data()),
                                 (int)in.size(), nullptr, 0);
    std::wstring w(wn, L'\0');
    MultiByteToWideChar(932, 0, reinterpret_cast<const char*>(in.data()),
                        (int)in.size(), &w[0], wn);
    for (size_t i = 0; i < w.size(); i++) {
        uint32_t cp = (uint16_t)w[i];
        if (cp >= 0xD800 && cp <= 0xDBFF && i + 1 < w.size()) {
            uint32_t lo = (uint16_t)w[i + 1];
            cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00);
            i++;
        }
        out.push_back(cp);
    }
    return out;
}
static Bytes codepointsToSjis(const std::vector<uint32_t>& cps) {
    std::wstring w;
    for (uint32_t cp : cps) {
        if (cp < 0x10000) w.push_back((wchar_t)cp);
        else {
            cp -= 0x10000;
            w.push_back((wchar_t)(0xD800 + (cp >> 10)));
            w.push_back((wchar_t)(0xDC00 + (cp & 0x3FF)));
        }
    }
    int n = WideCharToMultiByte(932, 0, w.c_str(), (int)w.size(),
                                nullptr, 0, nullptr, nullptr);
    Bytes out(n);
    if (n) WideCharToMultiByte(932, 0, w.c_str(), (int)w.size(),
                               reinterpret_cast<char*>(out.data()), n,
                               nullptr, nullptr);
    return out;
}
#endif

// ----------------------------------------------------------------------------
// Sharp character set  <->  Unicode code point
//
// Bytes not covered by the loaded table round-trip losslessly through the
// Unicode Private Use Area: Sharp byte 0xHH  <->  U+E000+HH. This guarantees a
// byte-perfect bas2text -> text2bas round trip even for glyphs we have not yet
// mapped, while still letting you read the parts we have.
// ----------------------------------------------------------------------------
static const uint32_t PUA_BASE = 0xE000;

struct Charset {
    uint32_t toUni[256];              // Sharp byte -> code point
    std::map<uint32_t, uint8_t> toSharp; // code point -> Sharp byte

    void buildDefault() {
        for (int b = 0; b < 256; b++) toUni[b] = PUA_BASE + b; // unknown -> PUA
        // printable ASCII is identity
        for (int b = 0x20; b <= 0x7E; b++) map((uint8_t)b, (uint32_t)b);
        // whitespace / control we care about
        map(0x09, 0x09); // TAB
        map(0x0A, 0x0A); // LF
        map(0x0D, 0x0D); // CR
        rebuildReverse();
    }
    void map(uint8_t b, uint32_t cp) { toUni[b] = cp; }
    void rebuildReverse() {
        toSharp.clear();
        for (int b = 0; b < 256; b++) {
            uint32_t cp = toUni[b];
            // first definition wins for a given code point
            if (toSharp.find(cp) == toSharp.end())
                toSharp[cp] = (uint8_t)b;
        }
    }

    // Load / override entries from a .tab file. Lines:
    //   HH  U+XXXX      ; comment      (map Sharp byte HH to code point XXXX)
    //   HH  =           ; explicitly undefined -> keep PUA fallback
    // '#' or ';' starts a comment. Blank lines ignored.
    bool loadFile(const std::string& path, std::string* err) {
        std::ifstream f(path);
        if (!f) { if (err) *err = "cannot open charset file: " + path; return false; }
        std::string line;
        int lineno = 0;
        while (std::getline(f, line)) {
            lineno++;
            // strip comments
            size_t c = line.find_first_of("#;");
            if (c != std::string::npos) line = line.substr(0, c);
            std::istringstream ls(line);
            std::string tokB, tokU;
            if (!(ls >> tokB)) continue; // blank
            unsigned b;
            if (sscanf(tokB.c_str(), "%x", &b) != 1 || b > 0xFF) {
                if (err) *err = path + ":" + std::to_string(lineno) + ": bad byte token";
                return false;
            }
            if (!(ls >> tokU)) continue; // byte with no mapping -> ignore
            if (tokU == "=") { toUni[b] = PUA_BASE + b; continue; }
            unsigned cp;
            const char* s = tokU.c_str();
            if (s[0] == 'U' && s[1] == '+') s += 2;
            else if (s[0] == '0' && (s[1] == 'x' || s[1] == 'X')) s += 2;
            if (sscanf(s, "%x", &cp) != 1) {
                if (err) *err = path + ":" + std::to_string(lineno) + ": bad code point token";
                return false;
            }
            toUni[b] = cp;
        }
        rebuildReverse();
        return true;
    }
};

// ----------------------------------------------------------------------------
// 16-byte binary-file header  (layout confirmed on real PC-E650 SAVE M files)
// ----------------------------------------------------------------------------
//   off  0..3  FF 00 06 01   file type: machine code   (constant)
//   off  4     10                                      (constant)
//   off  5..7  length,        24-bit little endian
//   off  8..10 start address, 24-bit little endian
//   off 11..13 FF FF FF                                (constant)
//   off 14..15 00 0F                                   (constant)
// Only the length and the start address vary; the other 11 bytes were identical
// in every captured file. Example (S3A.ROM, 0x40000 bytes loaded at 0xC0000):
//   ff 00 06 01 10 00 00 04 00 00 0c ff ff ff 00 0f
static const size_t HDR_LEN = 16;

// The constant bytes, at their offsets in the header.
static const uint8_t HDR_SIG[5]  = { 0xFF, 0x00, 0x06, 0x01, 0x10 };  // off 0..4
static const uint8_t HDR_TAIL[5] = { 0xFF, 0xFF, 0xFF, 0x00, 0x0F };  // off 11..15

static void put24le(Bytes& h, size_t at, uint32_t v) {
    h[at]     = (uint8_t)( v        & 0xFF);
    h[at + 1] = (uint8_t)((v >> 8)  & 0xFF);
    h[at + 2] = (uint8_t)((v >> 16) & 0xFF);
}

static uint32_t get24le(const Bytes& h, size_t at) {
    return (uint32_t)h[at] | ((uint32_t)h[at + 1] << 8) | ((uint32_t)h[at + 2] << 16);
}

// Build the 16-byte header for a raw image of the given start address and length.
static Bytes buildHeader(uint32_t addr, uint32_t length) {
    Bytes h(HDR_LEN, 0x00);
    std::memcpy(&h[0],  HDR_SIG,  sizeof(HDR_SIG));    // off  0..4
    put24le(h, 5,  length);                            // off  5..7
    put24le(h, 8,  addr);                              // off  8..10
    std::memcpy(&h[11], HDR_TAIL, sizeof(HDR_TAIL));   // off 11..15
    return h;
}

