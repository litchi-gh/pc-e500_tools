// conversions
// ----------------------------------------------------------------------------
struct Options {
    bool sjis        = false;   // treat PC text as Shift-JIS (CP932) instead of UTF-8
    bool sharpCR     = false;   // Sharp line terminator: CR only (default CR+LF)
    bool noEof       = false;   // do not append 0x1A EOF marker
    bool hostLF      = false;   // bas2text: output LF only (default CR+LF)
    bool asciiOnly   = false;   // ignore charset table, ASCII identity only
    uint32_t addr    = 0;       // bin2bas load address
    bool haveAddr    = false;
    std::string headerFile;     // bin2bas: inject this 16-byte header
    std::string saveHeader;     // bas2bin: write the stripped header here
    std::string charsetFile;    // explicit charset table path
};

static std::vector<uint32_t> decodePcText(const Bytes& in, const Options& o) {
#ifdef _WIN32
    if (o.sjis) return sjisToCodepoints(in);
#else
    if (o.sjis) die("Shift-JIS (--sjis) is only supported on the Windows build");
#endif
    return utf8ToCodepoints(in);
}

static Bytes encodePcText(const std::vector<uint32_t>& cps, const Options& o) {
#ifdef _WIN32
    if (o.sjis) return codepointsToSjis(cps);
#else
    if (o.sjis) die("Shift-JIS (--sjis) is only supported on the Windows build");
#endif
    Bytes out;
    for (uint32_t cp : cps) appendUtf8(out, cp);
    return out;
}

static int text2bas(const std::string& in, const std::string& out,
                    const Charset& cs, const Options& o) {
    Bytes raw = readFile(in);
    std::vector<uint32_t> cps = decodePcText(raw, o);

    Bytes result;
    size_t warnUnmapped = 0;
    for (size_t i = 0; i < cps.size(); i++) {
        uint32_t cp = cps[i];
        // normalise any of CRLF / CR / LF into the Sharp line terminator
        if (cp == 0x0D || cp == 0x0A) {
            if (cp == 0x0D && i + 1 < cps.size() && cps[i + 1] == 0x0A) i++; // eat CRLF pair
            result.push_back(0x0D);
            if (!o.sharpCR) result.push_back(0x0A);
            continue;
        }
        uint8_t b;
        if (o.asciiOnly) {
            if (cp <= 0x7F) b = (uint8_t)cp;
            else { b = '?'; warnUnmapped++; }
        } else if (cp >= PUA_BASE && cp <= PUA_BASE + 0xFF) {
            b = (uint8_t)(cp - PUA_BASE);               // PUA passthrough
        } else {
            auto it = cs.toSharp.find(cp);
            if (it != cs.toSharp.end()) b = it->second;
            else { b = '?'; warnUnmapped++; }
        }
        result.push_back(b);
    }
    if (!o.noEof) result.push_back(0x1A); // end-of-file marker

    writeFile(out, result);
    if (warnUnmapped)
        std::cerr << "ce140conv: warning: " << warnUnmapped
                  << " character(s) had no Sharp mapping and became '?'\n";
    std::cerr << "text2bas: wrote " << result.size() << " bytes to " << out << "\n";
    return 0;
}

static int bas2text(const std::string& in, const std::string& out,
                    const Charset& cs, const Options& o) {
    Bytes raw = readFile(in);
    if (!raw.empty() && raw[0] == 0xFF)
        std::cerr << "ce140conv: warning: input starts with 0xFF (looks like a "
                     "binary/LOAD M file). Did you mean bas2bin?\n";

    // drop a trailing EOF marker if present
    if (!raw.empty() && raw.back() == 0x1A) raw.pop_back();

    std::vector<uint32_t> cps;
    for (size_t i = 0; i < raw.size(); i++) {
        uint8_t b = raw[i];
        if (b == 0x0D) {
            if (i + 1 < raw.size() && raw[i + 1] == 0x0A) i++; // eat CRLF pair
            cps.push_back(o.hostLF ? 0x0A : 0x0D);
            if (!o.hostLF) cps.push_back(0x0A);
            continue;
        }
        if (b == 0x0A) { // lone LF
            cps.push_back(o.hostLF ? 0x0A : 0x0D);
            if (!o.hostLF) cps.push_back(0x0A);
            continue;
        }
        cps.push_back(o.asciiOnly ? (uint32_t)b : cs.toUni[b]);
    }

    Bytes result = encodePcText(cps, o);
    writeFile(out, result);
    std::cerr << "bas2text: wrote " << result.size() << " bytes to " << out << "\n";
    return 0;
}

static int bin2bas(const std::string& in, const std::string& out,
                   const Options& o) {
    Bytes payload = readFile(in);
    Bytes header;
    if (!o.headerFile.empty()) {
        header = readFile(o.headerFile);
        if (header.size() != HDR_LEN)
            die("--header file must be exactly " + std::to_string(HDR_LEN) +
                " bytes (got " + std::to_string(header.size()) + ")");
        if (header[0] != 0xFF)
            std::cerr << "ce140conv: warning: --header byte 0 is not 0xFF; the "
                         "emulator identifies binary files by a leading 0xFF\n";
    } else {
        uint32_t addr = o.haveAddr ? o.addr : 0;
        if (!o.haveAddr)
            std::cerr << "ce140conv: warning: no --addr given, using 0. Provide "
                         "the real load address for a correct LOAD M header.\n";
        if (addr > 0xFFFFFF)
            die("--addr does not fit in the 24-bit address field");
        if (payload.size() > 0xFFFFFF)
            die("payload is larger than the 24-bit length field (16777215 bytes)");
        header = buildHeader(addr, (uint32_t)payload.size());
    }
    Bytes result;
    result.reserve(header.size() + payload.size());
    result.insert(result.end(), header.begin(), header.end());
    result.insert(result.end(), payload.begin(), payload.end());
    writeFile(out, result);
    std::cerr << "bin2bas: wrote " << result.size() << " bytes ("
              << HDR_LEN << "-byte header + " << payload.size()
              << " payload) to " << out << "\n";
    return 0;
}

static int bas2bin(const std::string& in, const std::string& out,
                   const Options& o) {
    Bytes raw = readFile(in);
    if (raw.size() < HDR_LEN)
        die("input is shorter than a " + std::to_string(HDR_LEN) + "-byte header");
    if (raw[0] != 0xFF)
        std::cerr << "ce140conv: warning: input does not start with 0xFF; it may "
                     "be an ASCII file, not a binary/LOAD M file.\n";

    Bytes header(raw.begin(), raw.begin() + HDR_LEN);
    Bytes payload(raw.begin() + HDR_LEN, raw.end());

    if (!o.saveHeader.empty()) {
        writeFile(o.saveHeader, header);
        std::cerr << "bas2bin: saved " << HDR_LEN << "-byte header to "
                  << o.saveHeader << "\n";
    }
    writeFile(out, payload);
    std::cerr << "bas2bin: wrote " << payload.size()
              << " bytes (header stripped) to " << out << "\n";
    return 0;
}

static void hexDump(const Bytes& d, size_t count) {
    size_t n = std::min(count, d.size());
    for (size_t i = 0; i < n; i += 16) {
        char buf[8];
        std::snprintf(buf, sizeof(buf), "%04zx  ", i);
        std::cout << buf;
        for (size_t j = 0; j < 16; j++) {
            if (i + j < n) { std::snprintf(buf, sizeof(buf), "%02x ", d[i + j]); std::cout << buf; }
            else std::cout << "   ";
        }
        std::cout << " ";
        for (size_t j = 0; j < 16 && i + j < n; j++) {
            uint8_t b = d[i + j];
            std::cout << (char)((b >= 0x20 && b < 0x7F) ? b : '.');
        }
        std::cout << "\n";
    }
}

static int info(const std::string& in) {
    Bytes raw = readFile(in);
    std::cout << "file       : " << in << "\n";
    std::cout << "size       : " << raw.size() << " bytes\n";
    if (raw.empty()) { std::cout << "type       : (empty)\n"; return 0; }
    bool binary = raw[0] == 0xFF;
    std::cout << "first byte : 0x" << std::hex << (int)raw[0] << std::dec << "\n";
    std::cout << "type       : " << (binary ? "BINARY (LOAD M) - has 16-byte header"
                                            : "ASCII  (LOAD)") << "\n";
    if (binary) {
        size_t payload = raw.size() >= HDR_LEN ? raw.size() - HDR_LEN : 0;
        std::cout << "payload    : " << payload << " bytes (after "
                  << HDR_LEN << "-byte header)\n";
        std::cout << "header hex :\n";
        hexDump(Bytes(raw.begin(), raw.begin() + std::min(raw.size(), HDR_LEN)), HDR_LEN);
        if (raw.size() >= HDR_LEN) {
            Bytes h(raw.begin(), raw.begin() + HDR_LEN);
            uint32_t length = get24le(h, 5);
            uint32_t addr   = get24le(h, 8);
            char buf[64];
            std::snprintf(buf, sizeof(buf), "0x%06X (%u bytes)", length, length);
            std::cout << "length     : " << buf << "\n";
            std::snprintf(buf, sizeof(buf), "0x%05X-0x%05X", addr,
                          (unsigned)(addr + (payload ? payload - 1 : 0)));
            std::cout << "address    : " << buf << "\n";
            if (std::memcmp(&h[0], HDR_SIG, sizeof(HDR_SIG)) != 0 ||
                std::memcmp(&h[11], HDR_TAIL, sizeof(HDR_TAIL)) != 0)
                std::cout << "note       : constant header bytes differ from the "
                             "known SAVE M signature\n";
            if (length != payload)
                std::cout << "note       : header length and actual payload size "
                             "disagree\n";
        }
    } else {
        bool eof = raw.back() == 0x1A;
        std::cout << "eof marker : " << (eof ? "yes (0x1A)" : "no") << "\n";
        std::cout << "head hex   :\n";
        hexDump(raw, 64);
    }
    return 0;
}

